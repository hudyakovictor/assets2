function groupOf(n: number): CardGroup {
  if (n <= 15) return "green";
  if (n <= 24) return "yellow";
  if (n <= 33) return "blue";
  return "red";
}

export const SKILLS: SkillCard[] = rows.map(([plain, pro, idea], i) => {
  const n = i + 1;
  return { id: `c${String(n).padStart(2, "0")}`, group: groupOf(n), plain, pro, idea };
});

export const byId = (id: string) => SKILLS.find((s) => s.id === id) ?? SKILLS[0];

